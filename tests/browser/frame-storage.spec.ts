import {randomUUID} from 'node:crypto';
import {expect, test} from '../../frontend/node_modules/@playwright/test';

test('frame storage can be cleared without annotations loss and opening the video regenerates exact frames', async ({page, request}) => {
  const name='Frame storage '+randomUUID().slice(0,8);
  const project=await (await request.post('/api/projects',{data:{name,classes:['Person']}})).json();
  const pid=project.id;
  const vid=(await (await request.post(`/api/projects/${pid}/videos/local`,{data:{path:'tests/fixtures/numbered.mp4'}})).json()).video_id;
  await expect.poll(async()=>(await (await request.get(`/api/projects/${pid}`)).json()).videos[vid].status).toBe('ready');
  const identity={id:randomUUID(),person_id:7,name:'Track 7',class_name:'Person',box_styles:{'class:Person':{class_name:'Person',color:'#38bdf8'}}};
  const segment={id:randomUUID(),video_id:vid,identity_uuid:identity.id,start:0,end:null,status:'verified'};
  const box={id:randomUUID(),video_id:vid,frame_index:0,identity_uuid:identity.id,segment_id:segment.id,person_ext:null,person_visible:null,boxes:{'class:Person':[100,80,180,260]},full_quality:'unknown',occluded:null,truncated:null,geometry_link:'independent',review_state:'draft',evidence_note:'Keep this annotation',provenance:{'class:Person':{origin:'manual',proposal_id:null,human_corrected:false}}};
  const saved=await request.post(`/api/projects/${pid}/operations`,{data:{id:randomUUID(),base_revision:0,label:'Preserve frame-cache annotations',video_id:vid,frame_index:0,changes:[{collection:'identities',id:identity.id,before:null,after:identity},{collection:'segments',id:segment.id,before:null,after:segment},{collection:'observations',id:box.id,before:null,after:box}]}});
  expect(saved.ok(),await saved.text()).toBe(true);
  const before=await (await request.get(`/api/projects/${pid}`)).json();
  const ledger=await (await request.get(`/api/videos/${vid}/ledger`)).json();
  const frame=await (await request.get(`/api/videos/${vid}/frames/0`)).body();
  await page.route('**/api/updates/check*',route=>route.fulfill({json:{status:'current',current_version:'test',can_install:false}}));
  await page.goto('/');
  await page.getByTestId('open-project-'+pid).click();
  const row=page.getByTestId('video-row-'+vid);
  await expect(row.getByLabel('Select frame storage for numbered.mp4')).toBeEnabled();
  await row.getByLabel('Select frame storage for numbered.mp4').check();
  await page.getByRole('button',{name:'Clear selected frame storage (1)',exact:true}).click();
  await expect(page.getByRole('dialog')).toContainText('Source videos, tracks, boxes, IDs and editing history are kept');
  await page.getByRole('button',{name:'Cancel',exact:true}).click();
  expect((await (await request.get(`/api/videos/${vid}/frame-cache`)).json()).bytes).toBeGreaterThan(0);
  await page.getByRole('button',{name:'Clear selected frame storage (1)',exact:true}).click();
  await page.getByRole('button',{name:'Clear frame storage',exact:true}).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await expect(row).toContainText('Prepared on next open');
  expect((await (await request.get(`/api/videos/${vid}/frame-cache`)).json()).bytes).toBe(0);
  const cleared=await (await request.get(`/api/projects/${pid}`)).json();
  expect(cleared.state).toEqual(before.state);
  expect(cleared.revision).toBe(before.revision);
  await page.getByTestId('open-video-'+vid).click();
  await expect.poll(async()=>(await (await request.get(`/api/videos/${vid}/metadata`)).json()).status).toBe('ready');
  await expect(page.getByRole('button',{name:'Select Track 7',exact:true})).toBeVisible();
  await expect(page.getByTestId('canvas')).toHaveAttribute('data-frame','0');
  expect(await (await request.get(`/api/videos/${vid}/frames/0`)).body()).toEqual(frame);
  expect(await (await request.get(`/api/videos/${vid}/ledger`)).json()).toEqual(ledger);
  expect((await (await request.get(`/api/projects/${pid}`)).json()).state).toEqual(before.state);
  await expect.poll(async()=>(await (await request.get(`/api/videos/${vid}/frame-cache`)).json()).active).toBe(true);
  expect((await request.delete(`/api/videos/${vid}/frame-cache?confirmed=true`)).status()).toBe(409);
});
